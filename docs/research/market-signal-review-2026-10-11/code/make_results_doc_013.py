#!/usr/bin/env python3
"""Write docs/EXP_013_RESULTS.md from experiments/EXP-013 (and the feature-only description of the amendment variable).

Every number in the tables is read from the study's output files. The one extra computation (how many firms and dates carry a non-zero amendment count in the validation rows) uses features only, no label and no
return. The script refuses to run unless the attribution labels are the ones the prose was written for.

    .venv/bin/python docs/research/market-signal-review-2026-10-11/code/make_results_doc_013.py
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[4]
EXP = REPO / "experiments" / "EXP-013"
NAMES = {"amended": "rel_amended_730_xs", "latest": "rel_latest_amended_xs", "count": "rel_periodic_count_xs", "lagdet": "rel_lag_deterioration_xs", "missing": "rel_missing_xs", "u": "rel_u_xs"}


def main() -> None:
    manifest = json.loads((EXP / "manifest.json").read_text())
    labels = manifest["attribution"]
    if labels != {"P": "CARRIES", "M": "SHARES", "U": "NOT_CARRYING"}:
        sys.exit(f"the prose of this document was written for P CARRIES, M SHARES, U NOT_CARRYING; got {labels}")
    attr = json.loads((EXP / "attribution.json").read_text())
    ic = attr["mean_rank_ic"]
    paired = {r["contrast"]: r for r in csv.DictReader((EXP / "paired_tests.csv").open())}
    gain = ic["B5"] - ic["B1"]
    f = lambda r, k: float(r[k])
    acc = manifest["acceptance"]

    # features-only description of the amendment variable on the validation rows
    rel = pd.read_parquet(REPO / "data/research/derived/reliability_v1.parquet", columns=["date", "symbol", "amended_730"])
    rows = pd.read_parquet(REPO / "experiments/EXP-012/checkpoints/A1_0.parquet", columns=["date", "symbol", "fold"])
    d = rows.merge(rel, on=["date", "symbol"], how="left")
    flagged = d["amended_730"].fillna(0) > 0
    per_date = d.assign(nz=flagged).groupby("date")["nz"].sum()
    top10 = d.loc[flagged].groupby("symbol").size().sort_values(ascending=False).head(10).sum() / int(flagged.sum())
    fold_share = d.assign(nz=flagged).groupby("fold")["nz"].mean()

    singles = "\n".join(
        f"| `{col}` | {ic['C_' + k]:.5f} | {(ic['C_' + k] - ic['B1']) / gain:+.2f} | {f(paired['add_' + k], 'mean_diff'):+.5f} (t {f(paired['add_' + k], 'hac_t'):.2f}, {paired['add_' + k]['positive_folds']}/8) | "
        f"{ic['D_' + k]:.5f} | {(ic['B5'] - ic['D_' + k]) / gain:+.2f} | {f(paired['drop_' + k], 'mean_diff'):+.5f} (t {f(paired['drop_' + k], 'hac_t'):.2f}, {paired['drop_' + k]['positive_folds']}/8) |"
        for k, col in NAMES.items())
    groups = []
    for g in ("P", "M", "U"):
        a, c, pp, ps, dr = attr["groups"][g], paired[f"G_{g}"], paired[f"{g}_vs_perm"], paired[f"{g}_vs_shift"], paired[f"{g}_drop"]
        groups.append(f"| {g} | {a['what']} | {f(c, 'mean_diff'):+.5f} (t {f(c, 'hac_t'):.2f}, p {f(c, 'p_one_sided'):.3f}, {c['positive_folds']}/8) | {f(c, 'holm_adjusted_p'):.3f} | "
                      f"{f(pp, 'mean_diff'):+.5f} (t {f(pp, 'hac_t'):.2f}, p {f(pp, 'p_one_sided'):.3f}) | {f(ps, 'mean_diff'):+.5f} (t {f(ps, 'hac_t'):.2f}, p {f(ps, 'p_one_sided'):.3f}) | "
                      f"{f(dr, 'mean_diff'):+.5f} (t {f(dr, 'hac_t'):.2f}) | {a['add_share']:+.2f} | {a['drop_share']:+.2f} | **{a['label']}** |")
    doc = f"""# EXP-013 - which columns carry the EXP-012 T1 gain? (results summary)

Status: **COMPLETE, immutable.** Exploratory attribution on the same validation folds; validation-period evidence only. **Promotion NOT ASSESSED; nothing promoted.** Holdout: **untouched** (firewall state
`{manifest['holdout']['firewall']['holdout_state']}`). Preregistration: [EXP_013_PREREGISTRATION.md](EXP_013_PREREGISTRATION.md), registration commit `{manifest['registration_commit'][:12]}`, definition fingerprint
`{manifest['definition_fingerprint'][:16]}...`. Outputs: `experiments/EXP-013/`, run at commit `{manifest['git_commit'][:12]}` on a clean tree (`git_dirty` is `{str(manifest['git_dirty']).lower()}`), {manifest['compute']['workers']} workers,
{manifest['compute']['wall_seconds']:.0f} s. Generated by `docs/research/market-signal-review-2026-10-11/code/make_results_doc_013.py` from those files. **This is an attribution check, not a confirmation of T1.**

## 1. Gates

Arms B1 and B5 reproduce EXP-012's A1 and A5 mean Rank IC to {acc['reproduction_abs_difference']['B1']:.1e} and {acc['reproduction_abs_difference']['B5']:.1e} (tolerance 1e-9); every prediction is finite; no date after
{acc['panel_end']}; the gain being attributed is IC(B5) - IC(B1) = {gain:+.5f}, as in EXP-012 (t {f(paired['total'], 'hac_t'):.2f}).

## 2. Attribution labels (rule fixed before any result: `docs/EXP_013_PREREGISTRATION.md`, section 5)

| Group | What | Add to the rich set (difference, t, p, folds) | Holm p (3 groups) | Add vs permuted placebo | Add vs shifted placebo | Removing it from the full block | Add share | Drop share | Label |
|---|---|---|---|---|---|---|---|---|---|
""" + "\n".join(groups) + f"""

**CARRIES** requires a resolvable add contrast (one-sided p < 0.10), add and drop shares of at least 0.5, both placebos beaten, a permuted-placebo difference with p < 0.10 and at least six positive folds. These are
descriptive labels. The Holm-adjusted p of the leading group (P) is {f(paired['G_P'], 'holm_adjusted_p'):.3f}: it does not clear 0.05 even among three descriptive contrasts.

## 3. One column at a time

| Column | Added alone: Rank IC | share of gain | difference from B1 | Removed from the full block: Rank IC | share lost | B5 minus arm |
|---|---|---|---|---|---|---|
{singles}

## 4. What this says

- **The gain is carried by the filing-process ranks, and chiefly by the amendment count.** The four ranks together add {f(paired['G_P'], 'mean_diff'):+.5f} to the rich set ({(ic['C_P'] - ic['B1']) / gain:.0%} of the gain,
  positive in {paired['G_P']['positive_folds']} of 8 folds) and removing them from the full block loses {f(paired['P_drop'], 'mean_diff'):+.5f} ({(ic['B5'] - ic['D_P']) / gain:.0%}). They beat both placebos, including the
  shifted one (margin {f(paired['P_vs_shift'], 'mean_diff'):+.5f}, p {f(paired['P_vs_shift'], 'p_one_sided'):.3f}). Within them, `rel_amended_730_xs` alone adds {f(paired['add_amended'], 'mean_diff'):+.5f} (t {f(paired['add_amended'], 'hac_t'):.2f},
  {paired['add_amended']['positive_folds']} of 8 folds); lateness deterioration, the regularity count and the latest-report-amended flag add nothing on their own. (In the final EXP-012 A5 model, an in-sample fit, the amendment rank's coefficient is negative: more recent amendments, lower predicted rank.)
- **The composite adds nothing** ({f(paired['G_U'], 'mean_diff'):+.5f}, {paired['G_U']['positive_folds']} of 8 folds) and **the missing-fundamentals count shares part of the gain** ({(ic['C_missing'] - ic['B1']) / gain:.0%}, p
  {f(paired['G_M'], 'p_one_sided'):.3f}) without beating a one-year-shifted version of itself (margin {f(paired['M_vs_shift'], 'mean_diff'):+.5f}), which fits a persistent firm trait.
- **The registration's prior expectation was wrong.** It expected the composite and lateness deterioration to carry most of the gain and the amendment ranks almost none, because those are nearly constant. The opposite
  held for the amendment count, which is constant for 97% of rows but not for the rows that matter.

## 5. What this does not say

1. *The amendment effect rests on few firms.* In the {len(d):,} validation rows only {int(flagged.sum()):,} ({flagged.mean():.1%}) have an amendment in the trailing two years; these come from {d.loc[flagged, 'symbol'].nunique()} distinct
   symbols of {d['symbol'].nunique()} ({d.loc[flagged, 'symbol'].nunique() / d['symbol'].nunique():.1%}), about {per_date.mean():.1f} names per date (maximum {int(per_date.max())}); the ten most frequent symbols hold {top10:.0%} of the
   flagged rows. Each amendment stays visible for 730 days, so the independent episodes are far fewer than the rows. The date-level Newey-West statistic does not account for clustering by firm; a t of about 2 from a few dozen
   firm-episodes is fragile. No firm-level or event-level analysis has been done.
2. *It thins out over time.* The flagged share falls from {fold_share.iloc[0]:.1%} in the first fold to {fold_share.iloc[-1]:.1%} in the last, and the EXP-012 gain is absent in the last two folds, where there are fewest events.
3. *An amendment is not a restatement.* The filing registry holds re-filed financial reports; some amendments are corrections, others are not. The variable is a proxy.
4. *It may be a known result.* Restatements and the returns that follow them are studied (Palmrose, Richardson and Scholz; Hribar and Jenkins; Frieder and Shanthikumar, "After a Restatement: Long-Run Market and Investor
   Response", 2008, whose abstract could not be retrieved). What is new here, if anything, is the point-in-time state-variable construction, not the idea that firms that have just corrected their reports earn different subsequent returns.
5. *Another look at reused folds.* The labels are descriptive, the Holm-adjusted p of the leading group is not below 0.05, and the single-column result (t {f(paired['add_amended'], 'hac_t'):.2f}) is one of twelve unadjusted
   single-column contrasts. T1 remains a lead, not a finding.
6. *No profit claim.* Economics are exploratory; nothing was promoted.

## 6. What would settle it (proposals, not enacted)

An event-level analysis, separately registered: the firms and episodes behind the amendment count, leave-one-firm-out and firm-clustered inference, returns before and after the amendment, and the effect of excluding
duplicate or Part III-type amendments; a build from the full EDGAR submission index (all amendments, late-filing notices, non-reliance events) on a larger universe; and, if the owner chooses, one frozen look at the sealed
holdout.

## 7. Reproduction

```bash
.venv/bin/python -m scripts.quant.exp013 gate
caffeinate -dimsu .venv/bin/python -m scripts.quant.exp013 run --workers 6
.venv/bin/python docs/research/market-signal-review-2026-10-11/code/make_results_doc_013.py
```
"""
    (REPO / "docs" / "EXP_013_RESULTS.md").write_text(doc)
    print("written", len(doc), "characters")


if __name__ == "__main__":
    main()

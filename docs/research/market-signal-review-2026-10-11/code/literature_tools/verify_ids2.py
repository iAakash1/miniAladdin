import json, time, urllib.request, urllib.parse, http.client, xml.etree.ElementTree as ET
UA = "omnisignal-literature-check/1.0 (research; no contact)"
def get(url, tries=5):
    last = None
    for i in range(tries):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept-Encoding": "identity"})
            with urllib.request.urlopen(req, timeout=60) as r:
                return r.read()
        except http.client.IncompleteRead as e:
            last = e; time.sleep(1.5 * (i + 1))
        except Exception as e:
            last = e; time.sleep(1.5 * (i + 1))
    raise last
out = {}
for k, d in {"hlz_2016_rfs": "10.1093/rfs/hhv059", "cmn_2020_jf": "10.1111/jofi.12885"}.items():
    try:
        j = json.loads(get("https://api.crossref.org/works/" + urllib.parse.quote(d)))["message"]
        out[k] = {"doi": d, "title": (j.get("title") or [""])[0], "container": (j.get("container-title") or [""])[0], "year": (j.get("issued", {}).get("date-parts") or [[None]])[0][0],
                  "volume": j.get("volume"), "issue": j.get("issue"), "page": j.get("page"), "authors": [f"{a.get('family','')}, {a.get('given','')}" for a in j.get("author", [])], "type": j.get("type")}
    except Exception as e:
        out[k] = {"doi": d, "error": repr(e)[:200]}
titles = {
 "glasserman_lin": "Assessing Look-Ahead Bias in Stock Return Predictions Generated By GPT Sentiment Analysis",
 "bali_mfd": "Machine Forecast Disagreement",
 "goulding_dod": "Disagreement of Disagreement",
 "bracher_funk": "Information leakage from data revisions in retrospective forecasts",
 "sanderink": "When Alpha Breaks: Two-Level Uncertainty for Safe Deployment of Cross-Sectional Stock Rankers",
 "lookahead_bench": "Look-Ahead-Bench: a Standardized Benchmark of Look-ahead Bias in Point-in-Time LLMs for Finance",
 "fog": "Forecasting in the Fog: Real-Time versus Revised-Data Evidence on Machine Learning Edge over the Phillips Curve",
 "aygun_era": "An AI system to help scientists write expert-level empirical software",
}
for k, t in titles.items():
    try:
        q = urllib.parse.urlencode({"query.bibliographic": t, "rows": 3})
        items = json.loads(get("https://api.crossref.org/works?" + q))["message"]["items"]
        out[k] = [{"doi": i.get("DOI"), "title": (i.get("title") or [""])[0], "container": (i.get("container-title") or [""])[0], "year": (i.get("issued", {}).get("date-parts") or [[None]])[0][0],
                   "volume": i.get("volume"), "issue": i.get("issue"), "page": i.get("page"), "type": i.get("type"), "first_author": (i.get("author") or [{}])[0].get("family"), "score": i.get("score")} for i in items]
    except Exception as e:
        out[k] = {"error": repr(e)[:200]}
    time.sleep(0.4)
ids = ["0810.1922", "1505.02463", "2309.17322", "2601.13770", "2603.13252", "2608.05883", "2608.09033"]
arx = {}
for aid in ids:
    try:
        x = get("http://export.arxiv.org/api/query?id_list=" + aid)
        ns = {"a": "http://www.w3.org/2005/Atom", "ar": "http://arxiv.org/schemas/atom"}
        root = ET.fromstring(x)
        for e in root.findall("a:entry", ns):
            arx[aid] = {"title": " ".join(e.find("a:title", ns).text.split()), "published": e.find("a:published", ns).text, "updated": e.find("a:updated", ns).text,
                        "authors": [a.find("a:name", ns).text for a in e.findall("a:author", ns)],
                        "journal_ref": (e.find("ar:journal_ref", ns).text if e.find("ar:journal_ref", ns) is not None else None),
                        "doi": (e.find("ar:doi", ns).text if e.find("ar:doi", ns) is not None else None)}
    except Exception as e:
        arx[aid] = {"error": repr(e)[:200]}
    time.sleep(3.2)
out["arxiv"] = arx
print(json.dumps(out, indent=1))

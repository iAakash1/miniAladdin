#!/usr/bin/env python3
"""Phase II continuation: screening ledger, evidence matrix and coverage numbers for the 2022-2026 literature update.

Reads `recent_lit_candidates.csv` (from `merge_recent_lit.py`), `recent_core_crossref.csv`, `lead_verification.csv`, `recent_lit_matrix_data.py` and the request logs; writes
    recent_lit_screening.csv   one row per work whose title I read (reading set), with the decision, the class and the reason
    recent_lit_matrix.csv      the long per-paper field set for the core papers (publication facts joined from Crossref by DOI)
    recent_lit_coverage.json   every count quoted in 17_RECENT_LITERATURE_2022_2026.md
and adds `screen_stage` and `decision` columns to `recent_lit_candidates.csv`.

Stages: L0 retrieved (raw records) -> deduplicated works -> L1 rule filter (domain term, topical keyword; nothing read) -> L2 reading set (titles read by me, abstracts for the ones in the matrix) -> L3 included
(core = in the matrix; context = listed) or excluded with a reason. "Read" never means more than that: a work outside the reading set was only rule-filtered.

    .venv/bin/python docs/research/market-signal-review-2026-10-11/code/build_recent_lit_report.py
"""

from __future__ import annotations

import csv
import html
import json
import re
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from recent_lit_matrix_data import ROWS  # noqa: E402

NA = "NR (not read: the abstract does not state it, or the full text was not available)"
FIN_VENUE = re.compile(
    r"journal of finance|journal of financial economics|review of financial studies|journal of financial and quantitative|management science|review of finance|journal of accounting research|journal of accounting and economics|"
    r"accounting review|contemporary accounting|review of accounting studies|journal of business finance|european financial management|journal of empirical finance|journal of financial markets|journal of banking|"
    r"financial analysts journal|journal of portfolio|review of asset pricing|journal of financial data|critical finance|journal of econometrics|journal of applied econometrics|econometrica|journal of political economy|"
    r"quarterly journal of economics|american economic|accounting horizons|accounting organizations|auditing|review of quantitative finance|journal of corporate finance|financial management|financial review|"
    r"journal of international financial markets|international review of financial analysis|finance research letters|journal of economic dynamics|journal of forecasting|international journal of forecasting|"
    r"accounting and finance|accounting & finance|journal of accounting, auditing|journal of financial reporting|journal of information systems|advances in accounting|abacus|european accounting review|"
    r"china journal of accounting|review of accounting|ssrn|nber|arxiv|working paper|osf|research square|repec", re.I)
RETURNISH = re.compile(r"return|stock|cross-section|asset pric|equity|anomal|portfolio|factor|characteristic", re.I)
Q_RETURN = re.compile(r"return|predict|anomal|mispric|drift|cross-section|asset pric|cost of (equity|capital)", re.I)
# titles read in the restatement-titled group that are not about finance or accounting at all
NOT_FINANCE = re.compile(r"torts|property|contract|restitution|conflicts|fermi|aircraft|stealth (assessment|marketing|adapted|maneuver)|metasurface|laser|immigration|delaware|dingle|kalecki|democracy|usul|medis|"
                         r"constitutional|trademark|employment law|common law|legal realism|corporate elections|biodiversity|educational games|restatement of (the )?law|restatements as law|relying on restatements|"
                         r"third restatement|restatement \(fourth\)|pembentukan|hukum|non-reliance (commitment|on words)|magic|disgusted|moelis", re.I)
CONSEQUENCE = re.compile(r"investor|market|stock|return|price|short|trading|analyst|cost of (equity|capital)|reaction|shareholder|lending|credit|spillover|contagion|institutional|value|recommendation|repurchase|tax|dividend|"
                         r"investment|trade credit|customer|supplier|cds|bank", re.I)
DETECTION = re.compile(r"predict|detect|machine learning|learning|score|early warning|ai-|algorithm|misstatement risk|screening|forensic|data mining|explainable|neural|transformer|tabtransformer|fraud", re.I)
# works outside the restatement-titled group that I read and kept as context (design, point in time, reproducibility, data provenance, multiple testing)
CONTEXT_TITLES = re.compile(
    r"assessing look-ahead bias in stock return predictions generated by gpt|too good to be true: look-ahead bias in empirical options|fu \(2009\) positive relation|point-in-time data integrity in quantitative equity|"
    r"auditable public-data u\.s\. equity research pipeline|quantifying backtest overfitting from information leakage|lookahead bias in alpha factor models|do investors have data blind spots|fresh data, stale signals|"
    r"fresh or stale\? the impact of mispricing signal variability|false discovery rate in finance|correlated false discoveries|efficacy of multiple testing adjustments|publication bias in asset pricing|"
    r"replicating and digesting anomalies in the chinese|survivorship bias in the cross-section of winner|dead at the formation date|rebuilding the fama-french factor construction inside the point-in-time|"
    r"machine learning goes global|alpha go everywhere|stock picking with machine learning|automated stock picking using random forests|performance attribution of machine learning|"
    r"machine learning for stock return prediction: transformers|missing values handling for machine learning portfolios|empirical asset pricing via machine learning: the global edition|"
    r"can chatgpt forecast stock price movements|enhancing stock market anomalies with machine learning|option return predictability with machine learning|deep learning in characteristics-sorted factor models|"
    r"the context of earnings management and its ability to predict future stock returns|what affects factor loading uncertainty and expected returns|undetected accounting fraud|"
    r"when auc survives but portfolios do not|information leakage from data revisions|does xbrl tagging indicate disclosure quality|interpretable machine learning for asset pricing|from econometrics to machine learning|"
    r"asset pricing and machine learning: a critical review|identifying factor importance in empirical asset pricing|usefulness of credit ratings for accounting fraud prediction|predicting material misstatements using machine learning", re.I)
SWEEPS_OF_INTEREST = ("S3", "S4", "S9", "S10")


def read_csv(path: Path) -> list[dict]:
    with path.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def main() -> int:
    cands = read_csv(HERE / "recent_lit_candidates.csv")
    cross = {r["doi"].lower(): r for r in read_csv(HERE / "recent_core_crossref.csv")}
    by_matrix: dict[str, dict] = {}
    for r in ROWS:
        if r["doi"]:
            by_matrix[r["doi"].lower()] = r

    ledger = []
    stages: Counter = Counter()
    decisions: Counter = Counter()
    year_by_decision: dict[str, Counter] = {}
    for c in cands:
        dois = {d for d in c["doi"].lower().split("|") if d}
        in_matrix = next((by_matrix[d] for d in dois if d in by_matrix), None)
        domain, topical = int(c["domain"]), int(c["domain"]) and (int(c["s_R"]) or int(c["s_ML"]) or int(c["s_D"]) or int(c["s_P"]) or int(c["s_Q"]))
        finance_venue = bool(FIN_VENUE.search(c["venue"]))
        queries = c["queries"].split(";")
        reading = False
        reasons = []
        if int(c["t_R"]):
            reading, _ = True, reasons.append("restatement or amendment term in the title")
        if domain and finance_venue and (int(c["t_D"]) or int(c["t_P"])):
            reading = True
            reasons.append("design or point-in-time term in the title, finance or working-paper venue")
        if domain and finance_venue and int(c["t_ML"]) and RETURNISH.search(c["title"]) and (int(c["cited_by"]) >= 8 or int(c["n_queries"]) >= 3):
            reading = True
            reasons.append("machine-learning return-prediction title, cited or widely retrieved")
        if domain and finance_venue and any(f"OpenAlex:{s}" in queries for s in SWEEPS_OF_INTEREST):
            reading = True
            reasons.append("boolean sweep S3/S4/S9/S10 member")
        if domain and finance_venue and int(c["t_Q"]) and Q_RETURN.search(c["title"]):
            reading = True
            reasons.append("accounting-quality title with a return term")
        if in_matrix:
            reading = True
            reasons.append("matrix row " + in_matrix["id"])
        if reading:
            stage = "L2_title_read"
            title = c["title"]
            if in_matrix:
                decision = "EXCLUDE_RETRACTED" if in_matrix["evidence"] == "RETRACTED" else ("INCLUDE_CORE" if in_matrix["evidence"] != "TITLE_ONLY" else "INCLUDE_CORE_TITLE_ONLY")
                why = f"matrix {in_matrix['id']} ({in_matrix['relation']}, {in_matrix['evidence']})"
            elif int(c["t_R"]):
                if NOT_FINANCE.search(title) or not domain:
                    decision, why = "EXCLUDE_NOT_FINANCE", "legal, engineering or other non-finance use of the word"
                elif DETECTION.search(title) and not CONSEQUENCE.search(title):
                    decision, why = "INCLUDE_CONTEXT", "misstatement detection or prediction (label side, no return outcome)"
                elif CONSEQUENCE.search(title):
                    decision, why = "INCLUDE_CONTEXT", "consequences of restatements (market, investors, analysts, credit, taxes, spillovers)"
                else:
                    decision, why = "EXCLUDE_DETERMINANTS_AUDIT_GOVERNANCE", "determinants, governance, auditing or reviews: no market consequence, no detection or point-in-time content"
            elif CONTEXT_TITLES.search(title):
                decision, why = "INCLUDE_CONTEXT", "design, point-in-time, reproducibility, multiple testing or machine-learning return prediction"
            else:
                decision, why = "EXCLUDE_OFF_QUESTION", "read; does not bear on restatement or amendment signals, evaluation design or point-in-time data"
            ledger.append({"group": c["group"], "title": title, "authors": c["authors"], "year": c["year"], "venue": c["venue"], "doi": c["doi"], "cited_by": c["cited_by"], "reading_rule": "; ".join(reasons), "decision": decision, "reason": why})
        else:
            stage = "L1_off_domain" if not domain else ("L1_not_topical" if not topical else "L1_topical_rule_only")
            decision = "NOT_SCREENED_BY_READING"
        c["screen_stage"], c["decision"] = stage, decision
        stages[stage] += 1
        decisions[decision] += 1
        year_by_decision.setdefault(decision, Counter())[c["year"]] += 1

    fields = list(cands[0].keys())
    with (HERE / "recent_lit_candidates.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=fields)
        w.writeheader()
        w.writerows(cands)
    with (HERE / "recent_lit_screening.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(ledger[0].keys()))
        w.writeheader()
        w.writerows(sorted(ledger, key=lambda r: (r["decision"], r["year"], r["title"])))

    # matrix
    matrix_fields = ["id", "group", "citation", "doi", "venue", "volume", "issue", "pages_or_article", "status", "first_online", "print_or_issue_date", "evidence", "coverage", "question", "sample", "data", "treatment", "method", "timing", "validation",
                     "inference", "findings", "economics", "stated_limits", "apparent_limits", "overlap", "relation", "confidence", "cited_by_crossref"]
    out_rows = []
    for r in ROWS:
        x = cross.get(r["doi"].lower(), {}) if r["doi"] else {}
        row = {k: r.get(k, NA) for k in matrix_fields}
        row.update({"venue": html.unescape(x.get("venue", "")) or ("SSRN (working paper)" if r["doi"].startswith("10.2139/ssrn") else "NR"), "volume": x.get("volume", ""), "issue": x.get("issue", ""), "pages_or_article": x.get("pages", ""), "first_online": r.get("first_online") or x.get("published_online", "") or x.get("created", "") or "NR",
                    "print_or_issue_date": x.get("published_print", "") or x.get("issued", "") or "NR", "cited_by_crossref": x.get("cited_by_crossref", ""), "doi": r["doi"] or "none (arXiv / thesis)",
                    "status": r.get("status") or ("retracted" if r["evidence"] == "RETRACTED" else "published" if x.get("type") == "journal-article" else "working paper or preprint" if x else "see citation")})
        out_rows.append(row)
    with (HERE / "recent_lit_matrix.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=matrix_fields)
        w.writeheader()
        w.writerows(out_rows)

    # coverage numbers
    merge = json.loads((HERE / "recent_lit_merge_summary.json").read_text())
    log = read_csv(HERE / "recent_search_log.csv")
    chain = read_csv(HERE / "citation_chain_log.csv")
    leads = read_csv(HERE / "lead_verification.csv")
    ok = [r for r in log if r["http_status"] == "200"]
    succeeded = {(r["source"], r["query_id"]) for r in ok}
    failed_rows = [r for r in log if r["http_status"] != "200"]
    failed = [r for r in failed_rows if (r["source"], r["query_id"]) not in succeeded]           # never succeeded
    retried = [r for r in failed_rows if (r["source"], r["query_id"]) in succeeded]              # failed once, repeated, then succeeded
    sweeps = [r for r in log if re.fullmatch(r"S\d+", r["query_id"])]
    evid = Counter(r["evidence"] for r in ROWS)
    cov = {
        "window": "2022-01-01 to 2026-10-12 (publication date); pre-2022 work only through citation seeds, the Phase I corpus and the older papers named in the matrix",
        "requests": {"logged": len(log), "http_200": len(ok), "never_succeeded": [{"source": r["source"], "query_id": r["query_id"], "http_status": r["http_status"]} for r in failed],
                     "failed_then_repeated_successfully": [{"source": r["source"], "query_id": r["query_id"], "http_status": r["http_status"]} for r in retried],
                     "by_source_http_200": dict(Counter(r["source"] for r in ok)), "ranked_queries": len({r["query_id"] for r in log if re.fullmatch(r"T\d+[a-z]", r["query_id"])}), "boolean_sweeps": len({r["query_id"] for r in sweeps}), "curated_arxiv_queries": len({r["query_id"] for r in log if re.fullmatch(r"A\d+", r["query_id"])}), "nber_queries": len({r["query_id"] for r in log if re.fullmatch(r"N\d+", r["query_id"])}),
                     "sweeps_truncated_at_600": [r["query_id"] for r in sweeps if "TRUNCATED" in r["note"]], "sweep_match_counts": {r["query_id"]: int(r["total_hits"]) for r in sweeps if r["total_hits"]}},
        "citation_chains": {"seeds_tried": len(chain), "seeds_resolved": sum(1 for r in chain if r["resolved_openalex_id"]), "seeds_unresolved": [r["seed"] for r in chain if not r["resolved_openalex_id"]],
                            "citing_works_fetched": sum(int(r["n_citing_2022_2026"] or 0) for r in chain)},
        "merge": merge,
        "stages": dict(stages),
        "decisions": dict(decisions),
        "reading_set_size": len(ledger),
        "included_core": decisions["INCLUDE_CORE"] + decisions["INCLUDE_CORE_TITLE_ONLY"], "included_core_with_abstract_read": decisions["INCLUDE_CORE"], "included_core_title_only": decisions["INCLUDE_CORE_TITLE_ONLY"],
        "included_context": decisions["INCLUDE_CONTEXT"], "excluded_after_reading": sum(v for k, v in decisions.items() if k.startswith("EXCLUDE_")), "excluded_by_reason": {k: v for k, v in decisions.items() if k.startswith("EXCLUDE_")},
        "year_distribution_all": merge["year_distribution"], "year_distribution_included": {y: sum(year_by_decision.get(d, Counter())[y] for d in ("INCLUDE_CORE", "INCLUDE_CORE_TITLE_ONLY", "INCLUDE_CONTEXT")) for y in merge["year_distribution"]},
        "matrix_rows": len(ROWS), "matrix_evidence_levels": dict(evid), "matrix_rows_by_group": dict(Counter(r["group"] for r in ROWS)),
        "full_texts_examined": {"this_continuation": ["Frieder and Shanthikumar 2008 (all 60 pages)", "Ghosh et al. 2025/2026 (open-access HTML, sections named in the matrix)"],
                                "earlier_in_phase_II": 14, "total_distinct": 16},
        "leads": {"named": len(leads), "verified_by_doi_in_crossref_or_openalex": sum(1 for r in leads if r["openalex_found"] == "True" or r["crossref_found"] == "True"),
                  "retrieved_by_the_search_queries_alone": 7, "missed_by_the_search_queries": ["Kang, Ryu and Webb (2025, Financial Innovation)"]},
        "unavailable": {"bot_verification_or_refusal": ["SSRN abstract and download pages", "Wiley PDF of Lalwani et al. (paywalled despite an open-access flag)", "AAA (The Accounting Review, Accounting Horizons)", "ScienceDirect", "INFORMS", "Springer API pages for programmatic fetch (page loads in the browser)"],
                        "abstract_not_retrievable": [r["id"] + " " + r["citation"].split(".")[0] for r in ROWS if r["evidence"] == "TITLE_ONLY"], "retracted": [r["id"] for r in ROWS if r["evidence"] == "RETRACTED"]},
    }
    (HERE / "recent_lit_coverage.json").write_text(json.dumps(cov, indent=2, sort_keys=True), encoding="utf-8")
    print(json.dumps({k: cov[k] for k in ("stages", "decisions", "reading_set_size", "included_core", "included_context", "excluded_after_reading", "matrix_evidence_levels", "year_distribution_included")}, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())

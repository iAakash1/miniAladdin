def render_catalog(manifest: dict) -> str:
    cov = manifest["coverage"]
    lines = [
        "# PIT feature catalog (rich panel)", "",
        f"Dataset `{manifest['dataset_id']}` (`{manifest['panel_version']}`), {manifest['feature_count']} features = {manifest['baseline_feature_count']} unchanged baseline + {manifest['new_feature_count']} new. Generated from `src/quant/pit/rich_panel_catalog.py` and measured coverage.", "",
        "## Rules that apply to every new feature", "",
        f"* **Timestamp rule:** {COMMON['timestamp_rule']}.", f"* **Minimum lag:** {COMMON['minimum_lag']}.",
        f"* **Cross-sectional transform / winsorisation:** {COMMON['cross_sectional_transform']}.", f"* **Missing-value policy:** {COMMON['missing_policy']}.",
        "* **Source:** SEC Financial Statement Data Sets (`sec-core-facts-v3`) unless a column says otherwise; market cap uses the unadjusted close of the same date.", "",
        "## Baseline features (unchanged, identical values to `ds-491d761b9f2a6fc4`)", "",
        "`" + "`, `".join(R.BASELINE_FEATURES) + "`", "",
        "Price, liquidity, volatility, trend and market-regime features are PIT by construction (trailing windows only); the five rates features use the Treasury curve with a one-session lag (ALFRED vintages are `BLOCKED_EXTERNAL_FRED_KEY`).", ""]
    for family in ("profitability", "value", "investment", "quality", "leverage", "growth", "capital_structure", "event", "control"):
        names = [n for n in list(R.NEW_FEATURES) + list(R.CONTROL_FEATURES) if R.FAMILY.get(n) == family]
        if not names:
            continue
        lines += [f"## {family.replace('_', ' ').title()}", "", f"PIT assurance: {ASSURANCE[family]}.", "",
                  "| Feature | Formula | Inputs | First valid | Coverage | Known limitation |", "|---|---|---|---|---:|---|"]
        for name in names:
            col = f"{name}_xs"
            c = cov.get(col)
            first = c["first_valid_date"] if c else "withheld"
            share = pct(c["coverage"]) if c else "withheld"
            formula, inputs, limit = CATALOG[name]
            lines.append(f"| `{name}` | {formula} | {inputs} | {first} | {share} | {limit or '-'} |")
        lines.append("")
    return "\n".join(lines)



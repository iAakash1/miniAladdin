def main() -> int:
    (ROOT / "docs/PIT_SECURITY_MASTER_STATUS.md").write_text(render_security_master())
    manifest_path = ROOT / "data/manifests/rich_pit_panel_manifest.json"
    if manifest_path.exists():
        manifest = json.loads(manifest_path.read_text())
        (ROOT / "docs/PIT_FEATURE_CATALOG.md").write_text(render_catalog(manifest))
        (ROOT / "docs/RICH_PIT_PANEL_AUDIT.md").write_text(render_audit(manifest))
    print("rendered docs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
